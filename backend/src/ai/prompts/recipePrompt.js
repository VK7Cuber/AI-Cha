export function buildRecipePrompt({
  userProfileJson,
  ingredientsText,
  compatibilityText,
  baseRecipesText,
  dialogText
}) {
  return `
Ты — AI-бариста в чайном кафе. Твоя задача — придумать персонализированный рецепт напитка.
Создай уникальный рецепт на основе профиля клиента, диалога и доступных ингредиентов.

ПРОФИЛЬ КЛИЕНТА:
${userProfileJson}

ДОСТУПНЫЕ ИНГРЕДИЕНТЫ:
${ingredientsText}

ТАБЛИЦА СОВМЕСТИМОСТИ:
${compatibilityText}

БАЗОВЫЕ РЕЦЕПТЫ (для вдохновения):
${baseRecipesText}

ДИАЛОГ С ПОЛЬЗОВАТЕЛЕМ:
${dialogText}

ТРЕБОВАНИЯ:
1) Рецепт должен быть реализуем из доступных ингредиентов.
2) Рецепт должен соответствовать настроению и предпочтениям клиента.
3) Название и описание должны отражать реальные ингредиенты из списка "ingredients". Не упоминай вкусы/фрукты/ароматы,
   если их нет в доступных ингредиентах или в списке "ingredients".
4) Придумай красивое название напитка и включи в него 1–2 ключевых ингредиента из списка "ingredients".
5) Объясни, почему этот рецепт подходит именно этому клиенту.
6) Подробно опиши рецепт как последовательность действий.

Ответ строго в JSON формате:
{
  "name_ru": "Название напитка на русском",
  "name_zh": "Название на китайском (можно пустую строку)",
  "description_ru": "Описание напитка (2-3 предложения)",
  "reasoning_ru": "Почему этот напиток подходит клиенту",
  "ingredients": [
    {"ingredient_id": "uuid", "amount": "200мл", "note": "заварить при 80°C, 3 минуты"}
  ],
  "preparation_steps": [
    {"step": 1, "instruction": "Заварить основу 3 минуты при указанной температуре"}
  ],
  "temperature": "hot/cold/warm",
  "preparation_time_minutes": 5
}
`;
}
